import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { foundations } from '../src/theme/foundations.ts';

const target = new URL('../../../services/api/app/social/static/tokens.css', import.meta.url);
const colorNames = { background: 'bg', surface: 'surface', surfaceAlt: 'raised', border: 'border', text: 'text', textMuted: 'muted', primaryDark: 'pink', primary: 'primary', primarySoft: 'soft', free: 'green', warning: 'amber', danger: 'red', onBrand: 'on-brand', dangerSurface: 'danger-surface', successSurface: 'success-surface', focus: 'focus' };
const lines = Object.entries(colorNames).map(([name, css]) => `  --${css}: ${foundations.palettes.dark[name]};`);
for (const [name, value] of Object.entries(foundations.space)) lines.push(`  --space-${name}: ${value}px;`);
for (const [name, value] of Object.entries(foundations.radius)) lines.push(`  --radius-${name}: ${value}px;`);
lines.push(`  --radius: ${foundations.radius.card}px;`);
lines.push(`  --font-family: ${foundations.font.family === 'System' ? '-apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif' : foundations.font.family};`);
for (const [name, role] of Object.entries(foundations.type)) {
  lines.push(`  --type-${name}-size: ${role.fontSize}px;`, `  --type-${name}-line: ${role.lineHeight}px;`, `  --type-${name}-weight: ${role.fontWeight};`);
}
const output = `/* Generated by npm run design:tokens in apps/mobile. Edit theme/foundations.ts. */\n:root {\n${lines.join('\n')}\n}\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Staff tokens are stale. Run npm run design:tokens.');
  console.log('Native and staff design foundations are synchronized.');
} else {
  writeFileSync(target, output);
  console.log(fileURLToPath(target));
}
